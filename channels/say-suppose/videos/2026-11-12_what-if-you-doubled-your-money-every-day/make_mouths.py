"""Talking mouths for the drawn cast (owner, 2026-11-13, on the v2 cut: "lips movement to show who is speaking").

The puppet's own mouth opens and closes with its character's voice, frame by frame: no lip_sync model, no Wav2Lip
(both banned), only the rig's mouth shapes picked from the loudness of that character's lines. Reads the mixed
narration (narration/narration.wav, so mutes are honoured) and assets/narration/props.json (which line is whose);
writes scenes/mouths.ts. Run after every re-voice, from the repo root:

    .venv/bin/python channels/say-suppose/videos/2026-11-12_what-if-you-doubled-your-money-every-day/make_mouths.py
"""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
FPS = 30
RATE = 16000
OPEN_DB, O_DB = -9.0, -20.0  # below the line's own peak: wide open, a small "o", else the face's own mouth


def frame_db(wav: Path) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(wav), "-ac", "1", "-ar", str(RATE), "-f", "f32le", "-"],
        capture_output=True,
        check=True,
    ).stdout
    a = np.frombuffer(raw, np.float32)
    hop = RATE // FPS
    n = len(a) // hop
    rms = np.sqrt(np.mean(a[: n * hop].reshape(n, hop) ** 2, axis=1))
    return 20 * np.log10(rms + 1e-9)


def shapes(db: np.ndarray) -> list[int]:
    """1 open, 2 "o", 0 closed; a long open vowel flutters to "o" every third frame so the mouth never freezes."""
    peak = float(np.percentile(db, 95)) if len(db) else 0.0
    out, run = [], 0
    for v in db:
        k = 1 if v > peak + OPEN_DB else 2 if v > peak + O_DB else 0
        run = run + 1 if k == 1 else 0
        out.append(2 if k == 1 and run % 3 == 0 else k)
    return out


def runs(codes: list[int], start: int) -> list[int]:
    flat, i = [], 0
    while i < len(codes):
        j = i
        while j < len(codes) and codes[j] == codes[i]:
            j += 1
        if codes[i]:
            flat += [start + i, start + j, codes[i]]
        i = j
    return flat


def main(video: Path) -> Path:
    props = json.loads((video / "assets" / "narration" / "props.json").read_text(encoding="utf-8"))
    db = frame_db(video / "narration" / "narration.wav")
    talk: dict[str, list[int]] = {}
    for clip, line in zip(props["timeline"]["clips"], props["lines"], strict=True):
        who = line.get("speaker") or "narrator"
        if who == "narrator":
            continue
        a, b = clip["from"], min(len(db), clip["from"] + clip["frames"])
        talk.setdefault(who, []).extend(runs(shapes(db[a:b]), a))
    out = video / "scenes" / "mouths.ts"
    body = ",\n".join(f"  {json.dumps(k)}: [{', '.join(map(str, v))}]" for k, v in sorted(talk.items()))
    out.write_text(
        "// Generated by make_mouths.py from the mixed narration: [from, to, shape] runs per character, shape 1 open,\n"
        "// 2 a small o. Re-run it after every re-voice.\n"
        f"export const MOUTHS: Record<string, number[]> = {{\n{body},\n}};\n",
        encoding="utf-8",
    )
    return out


if __name__ == "__main__":
    print(main(Path(sys.argv[1]) if len(sys.argv) > 1 else HERE))
